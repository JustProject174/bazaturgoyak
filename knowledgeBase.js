const { createClient } = require('@supabase/supabase-js');
const natural = require('natural');
const winston = require('winston');
const logger = winston.createLogger({
    transports: [new winston.transports.Console()]
});

const BOOKING_URL = process.env.GAS_URL || process.env.BOOKING_URL || '';

// Инициализация Supabase клиента
const supabase = createClient(
  process.env.SUPABASE_URL,
  process.env.SUPABASE_ANON_KEY
);

const TfIdf = natural.TfIdf;
const tfidf = new TfIdf();
let knowledgeBase = [];
let semanticIndex = [];

// Функция для создания семантического индекса
function buildSemanticIndex() {
    tfidf.documents = [];
    semanticIndex = [];

    knowledgeBase.forEach((item, index) => {
        if (item.answer && item.answer.trim()) {
            const indexText = `${item.keywords.join(" ")} ${item.answer}`;
            tfidf.addDocument(indexText);
            semanticIndex.push({
                originalIndex: index,
                text: indexText,
                item: item,
            });
        }
    });

    console.log(`Семантический индекс построен для ${semanticIndex.length} записей`);
}

// Функция семантического поиска
function semanticSearch(query) {
    if (semanticIndex.length === 0) {
        console.log("Семантический индекс пуст");
        return null;
    }

    const scores = [];
    tfidf.tfidfs(query, (i, measure) => {
        if (measure > 0) {
            scores.push({
                index: i,
                score: measure,
                item: semanticIndex[i],
            });
        }
    });

    scores.sort((a, b) => b.score - a.score);

    if (scores.length > 0) {
        const bestMatch = scores[0];
        console.log(`Семантический поиск: найдено совпадение с релевантностью ${bestMatch.score.toFixed(4)}`);

        if (bestMatch.score > 30.0) {
            return bestMatch.item.item.answer;
        }
    }

    console.log("Семантический поиск: подходящих результатов не найдено");
    return null;
}

// Загрузка базы знаний из Supabase
async function loadKnowledgeBase() {
    try {
        const { data, error } = await supabase
            .from('knowledge_goldensands')
            .select('keywords, answer');

        if (error) {
            throw error;
        }

        knowledgeBase = data || [];
        console.log(`Загружено ${knowledgeBase.length} записей из базы знаний`);

        if (knowledgeBase.length === 0) {
            console.log("Таблица пуста, создаем начальную базу знаний...");
            await createInitialKnowledgeBase();
        }

        buildSemanticIndex();
        return knowledgeBase;
    } catch (error) {
        console.error("Ошибка загрузки базы знаний:", error);
        console.log("Создаем начальную базу знаний...");
        const result = await createInitialKnowledgeBase();
        return result;
    }
}

